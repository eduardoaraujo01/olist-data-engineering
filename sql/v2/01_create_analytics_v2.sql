-- Modelo dimensional V2 da Olist.
-- Cada tabela pertence a um batch_id específico.
-- Este arquivo cria a estrutura; ele não carrega dados.

CREATE SCHEMA IF NOT EXISTS analytics_v2;

CREATE TABLE IF NOT EXISTS analytics_v2.dim_customer (
    batch_id TEXT NOT NULL,
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id TEXT NOT NULL,
    customer_unique_id TEXT,
    customer_zip_code_prefix VARCHAR(5),
    customer_city TEXT,
    customer_state CHAR(2),

    PRIMARY KEY (batch_id, customer_key),
    UNIQUE (batch_id, customer_id)
);

CREATE TABLE IF NOT EXISTS analytics_v2.dim_date (
    batch_id TEXT NOT NULL,
    date_key INTEGER NOT NULL,
    full_date DATE NOT NULL,
    calendar_year SMALLINT NOT NULL,
    calendar_quarter SMALLINT NOT NULL
        CHECK (calendar_quarter BETWEEN 1 AND 4),
    calendar_month SMALLINT NOT NULL
        CHECK (calendar_month BETWEEN 1 AND 12),
    day_of_month SMALLINT NOT NULL
        CHECK (day_of_month BETWEEN 1 AND 31),
    iso_day_of_week SMALLINT NOT NULL
        CHECK (iso_day_of_week BETWEEN 1 AND 7),
    is_weekend BOOLEAN NOT NULL,

    PRIMARY KEY (batch_id, date_key),
    UNIQUE (batch_id, full_date)
);

CREATE TABLE IF NOT EXISTS analytics_v2.dim_order_status (
    batch_id TEXT NOT NULL,
    order_status_key BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_status TEXT NOT NULL,

    PRIMARY KEY (batch_id, order_status_key),
    UNIQUE (batch_id, order_status)
);

CREATE TABLE IF NOT EXISTS analytics_v2.fact_orders (
    batch_id TEXT NOT NULL,
    order_id TEXT NOT NULL,
    customer_key BIGINT,
    order_status_key BIGINT,

    purchase_date_key INTEGER,
    approved_date_key INTEGER,
    carrier_date_key INTEGER,
    delivered_date_key INTEGER,
    estimated_delivery_date_key INTEGER,

    order_purchase_at TIMESTAMP WITHOUT TIME ZONE,
    order_approved_at TIMESTAMP WITHOUT TIME ZONE,
    order_carrier_at TIMESTAMP WITHOUT TIME ZONE,
    order_delivered_at TIMESTAMP WITHOUT TIME ZONE,
    order_estimated_delivery_at TIMESTAMP WITHOUT TIME ZONE,

    delivery_days NUMERIC(10, 2),
    delivered_on_time BOOLEAN,

    PRIMARY KEY (batch_id, order_id),

    FOREIGN KEY (batch_id, customer_key)
        REFERENCES analytics_v2.dim_customer (batch_id, customer_key),

    FOREIGN KEY (batch_id, order_status_key)
        REFERENCES analytics_v2.dim_order_status (
            batch_id,
            order_status_key
        ),

    FOREIGN KEY (batch_id, purchase_date_key)
        REFERENCES analytics_v2.dim_date (batch_id, date_key),

    FOREIGN KEY (batch_id, approved_date_key)
        REFERENCES analytics_v2.dim_date (batch_id, date_key),

    FOREIGN KEY (batch_id, carrier_date_key)
        REFERENCES analytics_v2.dim_date (batch_id, date_key),

    FOREIGN KEY (batch_id, delivered_date_key)
        REFERENCES analytics_v2.dim_date (batch_id, date_key),

    FOREIGN KEY (batch_id, estimated_delivery_date_key)
        REFERENCES analytics_v2.dim_date (batch_id, date_key)
);

COMMENT ON TABLE analytics_v2.dim_customer IS
    'Clientes da Olist separados por lote; customer_unique_id pode se repetir.';

COMMENT ON TABLE analytics_v2.dim_date IS
    'Calendário do lote, reutilizado para as datas dos pedidos.';

COMMENT ON TABLE analytics_v2.dim_order_status IS
    'Status encontrados na fonte, separados por lote e sem reclassificação.';

COMMENT ON TABLE analytics_v2.fact_orders IS
    'Uma linha por pedido dentro de um lote; a chave é batch_id + order_id.';

COMMENT ON COLUMN analytics_v2.fact_orders.batch_id IS
    'Identificador do snapshot de origem ao qual este pedido pertence.';

COMMENT ON COLUMN analytics_v2.fact_orders.delivery_days IS
    'Dias entre compra e entrega; preenchido quando as datas são válidas.';

COMMENT ON COLUMN analytics_v2.fact_orders.delivered_on_time IS
    'TRUE quando a entrega ocorreu até a data estimada; NULL quando não é possível comparar.';
-- Índices nas colunas de referência para que reprocessamentos do lote
-- localizem as linhas filhas ao excluir/recarregar dimensões.
CREATE INDEX IF NOT EXISTS idx_fact_orders_batch_customer_key
    ON analytics_v2.fact_orders (batch_id, customer_key);
CREATE INDEX IF NOT EXISTS idx_fact_orders_batch_order_status_key
    ON analytics_v2.fact_orders (batch_id, order_status_key);
CREATE INDEX IF NOT EXISTS idx_fact_orders_batch_purchase_date_key
    ON analytics_v2.fact_orders (batch_id, purchase_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_orders_batch_approved_date_key
    ON analytics_v2.fact_orders (batch_id, approved_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_orders_batch_carrier_date_key
    ON analytics_v2.fact_orders (batch_id, carrier_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_orders_batch_delivered_date_key
    ON analytics_v2.fact_orders (batch_id, delivered_date_key);
CREATE INDEX IF NOT EXISTS idx_fact_orders_batch_estimated_delivery_date_key
    ON analytics_v2.fact_orders (batch_id, estimated_delivery_date_key);