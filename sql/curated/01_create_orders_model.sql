-- Modelo inicial para analisar pedidos e entregas da Olist.
-- Grão de fact_orders: uma linha por order_id.
-- Este arquivo cria a estrutura; ele não carrega dados.

CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE IF NOT EXISTS analytics.dim_customer (
    customer_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id TEXT NOT NULL UNIQUE,
    customer_unique_id TEXT,
    customer_zip_code_prefix VARCHAR(5),
    customer_city TEXT,
    customer_state CHAR(2)
);

CREATE TABLE IF NOT EXISTS analytics.dim_date (
    -- Convenção: date_key usa o formato numérico AAAAMMDD, por exemplo 20261007.
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    calendar_year SMALLINT NOT NULL,
    calendar_quarter SMALLINT NOT NULL CHECK (calendar_quarter BETWEEN 1 AND 4),
    calendar_month SMALLINT NOT NULL CHECK (calendar_month BETWEEN 1 AND 12),
    day_of_month SMALLINT NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    iso_day_of_week SMALLINT NOT NULL CHECK (iso_day_of_week BETWEEN 1 AND 7),
    is_weekend BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS analytics.dim_order_status (
    order_status_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_status TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS analytics.fact_orders (
    order_id TEXT PRIMARY KEY,
    customer_key BIGINT REFERENCES analytics.dim_customer (customer_key),
    order_status_key BIGINT REFERENCES analytics.dim_order_status (order_status_key),

    purchase_date_key INTEGER REFERENCES analytics.dim_date (date_key),
    approved_date_key INTEGER REFERENCES analytics.dim_date (date_key),
    carrier_date_key INTEGER REFERENCES analytics.dim_date (date_key),
    delivered_date_key INTEGER REFERENCES analytics.dim_date (date_key),
    estimated_delivery_date_key INTEGER REFERENCES analytics.dim_date (date_key),

    order_purchase_at TIMESTAMP WITHOUT TIME ZONE,
    order_approved_at TIMESTAMP WITHOUT TIME ZONE,
    order_carrier_at TIMESTAMP WITHOUT TIME ZONE,
    order_delivered_at TIMESTAMP WITHOUT TIME ZONE,
    order_estimated_delivery_at TIMESTAMP WITHOUT TIME ZONE,

    delivery_days NUMERIC(10, 2),
    delivered_on_time BOOLEAN
);

COMMENT ON TABLE analytics.dim_customer IS
    'Uma linha por customer_id da fonte Olist; customer_unique_id pode se repetir.';
COMMENT ON COLUMN analytics.dim_customer.customer_key IS
    'Chave substituta gerada no warehouse para relacionar fatos à dimensão.';
COMMENT ON COLUMN analytics.dim_customer.customer_id IS
    'Identificador natural da linha de cliente na fonte Olist; único nesta dimensão.';
COMMENT ON TABLE analytics.dim_date IS
    'Calendário reutilizado para diferentes datas dos pedidos.';
COMMENT ON TABLE analytics.dim_order_status IS
    'Lista dos valores de status encontrados na fonte, sem reclassificação de negócio.';
COMMENT ON TABLE analytics.fact_orders IS
    'Uma linha por pedido (order_id); datas e medidas derivadas preservam o grão do pedido.';
COMMENT ON COLUMN analytics.fact_orders.delivery_days IS
    'Dias entre compra e entrega ao cliente; preenchido somente quando ambas as datas são válidas. Valores negativos devem ser registrados como anomalia de qualidade, não descartados silenciosamente.';
COMMENT ON COLUMN analytics.fact_orders.delivered_on_time IS
    'TRUE quando a entrega ocorreu até a data estimada; NULL quando não há datas válidas para comparar.';
